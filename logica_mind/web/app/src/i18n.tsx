const STR: Partial<Record<Lang, Record<string, string>>> = { en: EN };
const LOADERS: Record<Lang, () => Promise<{ default: Record<string, string> }>> = {
  en: () => Promise.resolve({ default: EN }),
  pt: () => import("./locales/pt"),
  es: () => import("./locales/es"),
  zh: () => import("./locales/zh"),
  hi: () => import("./locales/hi"),
  ar: () => import("./locales/ar"),
  fr: () => import("./locales/fr"),
  ja: () => import("./locales/ja"),
  de: () => import("./locales/de"),
  ru: () => import("./locales/ru"),
  bn: () => import("./locales/bn"),
  id: () => import("./locales/id"),
  ko: () => import("./locales/ko"),
  it: () => import("./locales/it"),
  tr: () => import("./locales/tr"),
};
export async function loadLang(l: Lang): Promise<void> {
  if (STR[l]) return;
  try { STR[l] = (await LOADERS[l]()).default; } catch { /* keep English fallback */ }
}

export type TFn = (key: string, vars?: Record<string, string>) => string;

export function makeT(lang: Lang): TFn {
  return (key, vars) => {
    // the active language may not have loaded yet → fall back to English
    let s = (STR[lang] || EN)[key] ?? EN[key] ?? key;
    if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
    return s;
  };
}

export const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: TFn }>({
  lang: "en", setLang: () => {}, t: makeT("en"),
});
export const useI18n = () => useContext(LangCtx);

const LKEY = "lm-lang";
export function getLang(): Lang {
  const s = localStorage.getItem(LKEY) as Lang;
  if (LANGS.some((x) => x.code === s)) return s;
  // first visit: match the browser's language (e.g. 'pt-BR' → pt, 'zh-CN' → zh)
  const nav = (typeof navigator !== "undefined" ? navigator.language || "" : "").slice(0, 2).toLowerCase();
  return LANGS.some((x) => x.code === nav) ? (nav as Lang) : "en";   // else English
}
export function saveLang(l: Lang) { localStorage.setItem(LKEY, l); }
